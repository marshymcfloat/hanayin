"use client";

import * as React from "react";
import { format } from "date-fns";
import { Calendar as CalendarIcon } from "lucide-react";
import { cn } from "@/lib/utils";
import { Button } from "@/components/ui/button";
import { Calendar } from "@/components/ui/calendar";
import {
  Popover,
  PopoverContent,
  PopoverTrigger,
} from "@/components/ui/popover";
import ownerStyles from "./OwnerBookingForm.module.css";
import { useOptionalViewer } from "@/lib/auth/viewer-context";
import staffTheme from "@/components/dashboard/employee/StaffWorkspaceTheme.module.css";

interface DatePickerProps {
  value?: Date;
  onChange: (date: Date | undefined) => void;
  minDate?: Date;
  maxDate?: Date;
  placeholder?: string;
  /**
   * Map of `YYYY-MM-DD` (in business timezone) → slot count for the
   * visible booking horizon. Drives the density-dot indicator under
   * each date — gray for 0, primary/20 → /50 → primary for low/med/high.
   * Skip = no per-day data (hides the dots, picker behaves as before).
   */
  dayCapacity?: Record<string, number>;
  triggerLabel?: React.ReactNode;
  triggerClassName?: string;
  triggerAriaLabel?: string;
  presentation?: "default" | "owner";
  active?: boolean;
}

function dateKey(d: Date): string {
  // Use the local-date components, not toISOString(), since calendar
  // cell dates come from the user's locale. Server keys generated by
  // toPHDateString() align with this when the user is in PH; for
  // other timezones the picker will be off by at most one cell —
  // matches the `dayCapacity` lookup either way as long as both
  // sides use the same convention.
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

type DensityTier = "none" | "low" | "med" | "high";

function tierFor(count: number | undefined): DensityTier | null {
  if (count === undefined) return null;
  if (count === 0) return "none";
  if (count <= 3) return "low";
  if (count <= 8) return "med";
  return "high";
}

export default React.memo(function DatePicker({
  value,
  onChange,
  minDate = new Date(),
  maxDate,
  placeholder = "Pick a date",
  dayCapacity,
  triggerLabel,
  triggerClassName,
  triggerAriaLabel,
  presentation = "default",
  active = true,
}: DatePickerProps) {
  const owner = presentation === "owner";
  const staffDialogTheme = useOptionalViewer()?.actorType === "EMPLOYEE" ? staffTheme.workspace : "";
  const [open, setOpen] = React.useState(false);
  React.useEffect(() => {
    if (!active) setOpen(false);
  }, [active]);
  const minStart = new Date(minDate);
  minStart.setHours(0, 0, 0, 0);
  const maxEnd = maxDate ? new Date(maxDate) : undefined;
  if (maxEnd) {
    maxEnd.setHours(23, 59, 59, 999);
  }

  // Bucket dates into modifier sets so react-day-picker can apply
  // density classes per cell. We only run this when capacity data is
  // present to avoid pointless work on staff/legacy callers.
  const modifiers = React.useMemo(() => {
    if (!dayCapacity) return undefined;
    return {
      capNone: (date: Date) => tierFor(dayCapacity[dateKey(date)]) === "none",
      capLow: (date: Date) => tierFor(dayCapacity[dateKey(date)]) === "low",
      capMed: (date: Date) => tierFor(dayCapacity[dateKey(date)]) === "med",
      capHigh: (date: Date) => tierFor(dayCapacity[dateKey(date)]) === "high",
    };
  }, [dayCapacity]);

  // Each tier paints a 4px circular dot under the date number using
  // `::after`. The container is positioned via `relative` on the day
  // cell. cap-none keeps the date readable (no opacity collapse) so
  // the user can still click and see the empty-state alternatives.
  const modifiersClassNames = React.useMemo(
    () => ({
      capNone:
        "relative text-muted-foreground after:absolute after:bottom-0.5 after:left-1/2 after:-translate-x-1/2 after:size-1 after:rounded-full after:bg-muted-foreground/40",
      capLow:
        "relative after:absolute after:bottom-0.5 after:left-1/2 after:-translate-x-1/2 after:size-1 after:rounded-full after:bg-primary/20",
      capMed:
        "relative after:absolute after:bottom-0.5 after:left-1/2 after:-translate-x-1/2 after:size-1 after:rounded-full after:bg-primary/50",
      capHigh:
        "relative after:absolute after:bottom-0.5 after:left-1/2 after:-translate-x-1/2 after:size-1 after:rounded-full after:bg-primary",
    }),
    [],
  );

  return (
    <Popover open={open} onOpenChange={setOpen}>
      <PopoverTrigger asChild>
        <Button
          variant="outline"
          aria-label={triggerAriaLabel}
          className={cn(
            "w-full justify-start text-left font-normal",
            !value && "text-muted-foreground",
            owner && "min-h-14 rounded-[14px] border-[#DDE0D9] bg-white px-4 text-[#20211F] hover:border-[#72CF35] hover:bg-[#FAFBF8] focus-visible:ring-[#72CF35]",
            triggerClassName,
          )}
        >
          <CalendarIcon className="mr-2 h-4 w-4" />
          {triggerLabel ??
            (value ? format(value, "EEEE, MMMM d, yyyy") : placeholder)}
        </Button>
      </PopoverTrigger>
      <PopoverContent data-owner-booking-calendar={owner ? "" : undefined} className={cn("w-auto p-0", owner && ownerStyles.form, owner && "rounded-[18px] border-[#E7E9E4] p-2 shadow-[0_20px_50px_rgba(23,24,23,0.16)]", staffDialogTheme)} align="start">
        <Calendar
          mode="single"
          selected={value}
          onSelect={(date: Date | undefined) => {
            onChange(date);
            setOpen(false);
          }}
          disabled={(date: Date) =>
            date < minStart || (!!maxEnd && date > maxEnd)
          }
          modifiers={modifiers}
          modifiersClassNames={modifiersClassNames}
          initialFocus
        />
      </PopoverContent>
    </Popover>
  );
});
